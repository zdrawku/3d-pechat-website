// Downloads the web fonts the bookmark page's font list draws names with.
//
// The engine (`@printkit/bookmark-creator`) prints names in its own embedded TTFs; for
// the picker, `engineOptions().fonts[i]` gives the Google Fonts `family` + `weight` that
// look like what is printed. The site's CSP only allows its own fonts (`font-src 'self'`),
// so this copies the Latin and Cyrillic subsets of each into
// src/assets/fonts/bookmarks/ and writes the list the page registers them from
// (src/app/bookmarks/font-picker/bookmark-fonts.generated.ts).
//
// Run it again when the engine adds or changes a font: `node scripts/fetch-bookmark-fonts.mjs`
// (needs the network). The fonts are SIL Open Font License 1.1; their licences are copied
// from the package by angular.json.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { engineOptions } from '@printkit/bookmark-creator';

const OUT_DIR = 'src/assets/fonts/bookmarks';
const LIST = 'src/app/bookmarks/font-picker/bookmark-fonts.generated.ts';
const SUBSETS = ['latin', 'cyrillic'];
// A current browser's user agent, so Google Fonts answers with woff2 and unicode-range subsets.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

mkdirSync(OUT_DIR, { recursive: true });
const faces = [];
for (const font of engineOptions().fonts) {
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(font.family)}:wght@${font.weight}&display=swap`;
  const css = await (await fetch(url, { headers: { 'User-Agent': UA } })).text();
  // Each block: /* subset */ @font-face { … src: url(…) format('woff2'); unicode-range: …; }
  for (const [, subset, body] of css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]*)}/g)) {
    if (!SUBSETS.includes(subset)) {
      continue;
    }
    const src = /url\(([^)]+)\)/.exec(body)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1].trim();
    if (!src || !range) {
      continue;
    }
    const file = `${font.id}-${subset}.woff2`;
    writeFileSync(join(OUT_DIR, file), Buffer.from(await (await fetch(src)).arrayBuffer()));
    faces.push({ id: font.id, file, unicodeRange: range });
  }
  if (!faces.some((face) => face.id === font.id)) {
    throw new Error(`No web font found for ${font.id} (${font.family} ${font.weight})`);
  }
  console.log(`${font.id}: ${faces.filter((face) => face.id === font.id).map((face) => face.file).join(', ')}`);
}

writeFileSync(LIST, `// Generated by scripts/fetch-bookmark-fonts.mjs — do not edit by hand.
/** The web-font files that draw each engine font in the font list (assets/fonts/bookmarks/). */
export const BOOKMARK_FONT_FACES: readonly { id: string; file: string; unicodeRange: string }[] = ${JSON.stringify(faces, null, 2)};
`);
console.log(`${faces.length} files, list in ${LIST}`);
