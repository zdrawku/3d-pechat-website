const fs = require('fs');
const path = require('path');
const { fixInternalLinks, getValidPaths } = require('./auto-blog/internal-links');
const { readLocales } = require('./locale-urls');

// Blog article bodies must be available during prerendering (SSG), where
// runtime HTTP fetches don't happen. This generates TS modules that import
// every markdown file as a bundled string (see the ".md" loader in
// angular.json), keyed by slug, so the article components resolve posts synchronously:
//   - src/assets/blogs/*.md        → blog-content.generated.ts (Bulgarian, BlogService)
//   - src/assets/blogs/<code>/*.md → blog-content.translations.generated.ts (every
//     other language in src/i18n/locales.json)
// Each is its own lazy chunk, loaded by the post route's resolver for its
// language (src/app/blog/article/article.routes.ts).

const blogsDir = path.join(__dirname, '../src/assets/blogs');
const outputPath = path.join(__dirname, '../src/app/services/blog-content.generated.ts');
const translationsOutputPath = path.join(__dirname, '../src/app/services/blog-content.translations.generated.ts');

console.log('🔍 Generating blog content map from markdown files...');

const markdownIn = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f.endsWith('.md')).sort() : []);

// Normalise internal links in the markdown itself (absolute 3dpechat.bg URLs and
// slash-less paths -> canonical root-relative "/blog/slug/"), so hand-written and
// generated posts can't reintroduce links that GitHub Pages 301-redirects.
// Unknown internal links are unwrapped to plain text — reported loudly.
const validPaths = getValidPaths();
let rewritten = 0;
function normaliseLinks(dir, files) {
  for (const file of files) {
    const filePath = path.join(dir, file);
    const label = path.relative(blogsDir, filePath).replace(/\\/g, '/');
    const original = fs.readFileSync(filePath, 'utf8');
    const { markdown, dropped } = fixInternalLinks(original, validPaths);
    if (markdown !== original) {
      fs.writeFileSync(filePath, markdown, 'utf8');
      rewritten++;
      console.log(`🔗 Normalised internal links in ${label}`);
    }
    for (const link of dropped) {
      console.warn(`⚠️  ${label}: unknown internal link "${link}" was unwrapped to plain text`);
    }
  }
}

const files = markdownIn(blogsDir);
normaliseLinks(blogsDir, files);

// Translations: one folder per language, one file per entry in locales.json
// `translatedPosts`. A registered post without its file would prerender an
// empty page, so it stops the build; a file nobody registered is only reported.
const locales = readLocales();
const translations = [];
for (const { code } of locales.locales.filter(l => l.code !== locales.defaultLocale)) {
  const dir = path.join(blogsDir, code);
  const langFiles = markdownIn(dir);
  const registered = Object.values(locales.translatedPosts?.[code] ?? {});
  const slugs = new Set(langFiles.map(f => path.basename(f, '.md')));
  const missing = registered.filter(slug => !slugs.has(slug));
  if (missing.length) {
    console.error(`❌ src/i18n/locales.json lists ${code} posts without src/assets/blogs/${code}/<slug>.md: ${missing.join(', ')}`);
    process.exit(1);
  }
  for (const slug of slugs) {
    if (!registered.includes(slug)) {
      console.warn(`⚠️  src/assets/blogs/${code}/${slug}.md is not in locales.json translatedPosts.${code} — it won't be published`);
    }
  }
  normaliseLinks(dir, langFiles);
  translations.push({ code, files: langFiles.filter(f => registered.includes(path.basename(f, '.md'))) });
}
if (rewritten) console.log(`🔗 Normalised links in ${rewritten} markdown file(s)`);

const imports = files
  .map((file, i) => `import post${i} from ${JSON.stringify(`../../assets/blogs/${file}`)};`)
  .join('\n');

const entries = files
  .map((file, i) => `  ${JSON.stringify(path.basename(file, '.md'))}: post${i}`)
  .join(',\n');

const content = `// AUTO-GENERATED by scripts/generate-blog-content.js — do not edit manually.
${imports}

/** Lets scripts/preload-locale-chunks.js find this chunk in the build (dynamic imports keep every export). */
export const CHUNK_MARKER = "blog-content:bg";

export const BLOG_CONTENT: Record<string, string> = {
${entries}
};
`;

fs.writeFileSync(outputPath, content, 'utf8');
console.log(`✅ Blog content map generated with ${files.length} posts → src/app/services/blog-content.generated.ts`);

const translationImports = translations
  .flatMap(({ code, files: langFiles }) => langFiles.map((file, i) =>
    `import ${code}${i} from ${JSON.stringify(`../../assets/blogs/${code}/${file}`)};`))
  .join('\n');

const translationEntries = translations
  .map(({ code, files: langFiles }) => `  ${JSON.stringify(code)}: {\n${langFiles
    .map((file, i) => `    ${JSON.stringify(path.basename(file, '.md'))}: ${code}${i}`)
    .join(',\n')}\n  }`)
  .join(',\n');

const translationsContent = `// AUTO-GENERATED by scripts/generate-blog-content.js — do not edit manually.
${translationImports}

/** Lets scripts/preload-locale-chunks.js find this chunk in the build (dynamic imports keep every export). */
export const CHUNK_MARKER = "blog-content:translations";

/** Translated blog posts' markdown: language → the post's slug in that language → text. */
export const TRANSLATED_BLOG_CONTENT: Record<string, Record<string, string>> = {
${translationEntries}
};
`;

fs.writeFileSync(translationsOutputPath, translationsContent, 'utf8');
const translatedCount = translations.reduce((n, t) => n + t.files.length, 0);
console.log(`✅ Translated blog content map generated with ${translatedCount} posts → src/app/services/blog-content.translations.generated.ts`);
