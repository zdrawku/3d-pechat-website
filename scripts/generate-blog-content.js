const fs = require('fs');
const path = require('path');

// Blog article bodies must be available during prerendering (SSG), where
// runtime HTTP fetches don't happen. This generates a TS module that imports
// every markdown file as a bundled string (see the ".md" loader in
// angular.json), keyed by slug, so BlogService can resolve posts synchronously.

const blogsDir = path.join(__dirname, '../src/assets/blogs');
const outputPath = path.join(__dirname, '../src/app/services/blog-content.generated.ts');

console.log('🔍 Generating blog content map from markdown files...');

const files = fs.readdirSync(blogsDir)
  .filter(f => f.endsWith('.md'))
  .sort();

const imports = files
  .map((file, i) => `import post${i} from '../../assets/blogs/${file}';`)
  .join('\n');

const entries = files
  .map((file, i) => `  '${path.basename(file, '.md')}': post${i}`)
  .join(',\n');

const content = `// AUTO-GENERATED by scripts/generate-blog-content.js — do not edit manually.
${imports}

export const BLOG_CONTENT: Record<string, string> = {
${entries}
};
`;

fs.writeFileSync(outputPath, content, 'utf8');
console.log(`✅ Blog content map generated with ${files.length} posts → src/app/services/blog-content.generated.ts`);
