/**
 * Writes `.github/ISSUE_TEMPLATE/new-short.yml` (🎬 Ново кратко видео) with
 * one dropdown option per product in src/data/products.json. Runs in
 * prebuild, so a product added through `📦 Нов продукт` shows up in the form
 * in the same PR. Labels come from lib.FORM, which the parser reads back.
 */
const fs = require('fs');
const path = require('path');
const { ROOT, FORM, VOICES, readProducts } = require('./lib');

const FILE = path.join(ROOT, '.github', 'ISSUE_TEMPLATE', 'new-short.yml');

// JSON strings are valid YAML double-quoted scalars, so names with colons or
// quotes need no special handling.
const q = (s) => JSON.stringify(s);

function render(products) {
  const names = products.map((p) => p.name);
  const dupes = names.filter((n, i) => names.indexOf(n) !== i);
  if (dupes.length) throw new Error(`Product names must be unique for the short form: ${dupes.join(', ')}`);

  return `# GENERATED by scripts/make-short/generate-issue-form.js from src/data/products.json
# (runs in prebuild). Edit the generator, not this file.
name: 🎬 Ново кратко видео
description: Кратко видео за TikTok, YouTube Shorts и Reels за продукт от каталога. Само за екипа на сайта.
title: '[Видео]: '
labels: ['new-short']
body:
  - type: markdown
    attributes:
      value: |
        Избери продукта и добави снимки и клипове. Ботът пише текста на видеото и го пуска тук като коментар за одобрение.
        Отговори с \`/render\`, за да направи видеото, или с \`/redo\` и бележка за нова чернова.

        Видеата в GitHub са до 10 MB на файл. По-дългите клипове качи в папката на продукта в Google Drive и отметни полето „${FORM.drive}“.

        ⚠️ Работи само за екипа на сайта (\`.github/issue-authors.json\`). Issue-та от други акаунти се затварят автоматично.

  - type: dropdown
    id: product
    attributes:
      label: ${q(FORM.product)}
      description: Снимките на продукта от каталога се добавят сами.
      options:
${names.map((n) => `        - ${q(n)}`).join('\n')}
    validations:
      required: true

  - type: textarea
    id: media
    attributes:
      label: ${q(FORM.media)}
      description: Провлачи снимки и видеа тук. Видеото започва с клип, ако има такъв.
      placeholder: Провлачи файловете в това поле…
    validations:
      required: false

  - type: checkboxes
    id: drive
    attributes:
      label: ${q(FORM.drive)}
      options:
        - label: ${q(FORM.driveOption)}

  - type: textarea
    id: idea
    attributes:
      label: ${q(FORM.idea)}
      description: С какво да започне, какво да покаже, за кого е.
      placeholder: Започни с въртенето, после покажи монетите.
    validations:
      required: false

  - type: dropdown
    id: voice
    attributes:
      label: ${q(FORM.voice)}
      options:
${Object.keys(VOICES).map((v) => `        - ${q(v)}`).join('\n')}
      default: 0
    validations:
      required: true
`;
}

if (require.main === module) {
  const next = render(readProducts());
  const prev = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8') : '';
  if (next !== prev) {
    fs.writeFileSync(FILE, next);
    console.log(`[make-short] updated ${path.relative(ROOT, FILE)}`);
  }
}

module.exports = { render, FILE };
