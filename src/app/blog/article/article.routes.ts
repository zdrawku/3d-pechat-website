import { CanMatchFn, ResolveFn, Route } from '@angular/router';

import { DEFAULT_LOCALE, Locale, TRANSLATED_POSTS } from '../../i18n/locales';

/** What the article component gets from its route: the post's Bulgarian slug and its text in the page's language. */
export interface ArticleData {
  source: string;
  text: string | undefined;
}

/**
 * The Bulgarian slug of the post at `slug` in `locale` — the post's key
 * everywhere (registry, related content, SEO) — or undefined for an unknown
 * slug. Bulgarian slugs are checked against the registry, imported lazily so
 * that it stays out of the main bundle.
 */
export async function postSource(slug: string, locale: Locale): Promise<string | undefined> {
  if (locale !== DEFAULT_LOCALE) {
    return Object.entries(TRANSLATED_POSTS[locale] ?? {}).find(([, translated]) => translated === slug)?.[0];
  }
  const { BLOG_POSTS } = await import('../../services/blog-posts.registry');
  return BLOG_POSTS.some((post) => post.slug === slug) ? slug : undefined;
}

/** Matches only a post that exists in `locale`; any other slug falls through to the 404 route. */
export const isPostIn = (locale: Locale): CanMatchFn => async (_route, segments) =>
  segments.length === 1 && (await postSource(segments[0].path, locale)) !== undefined;

/**
 * The post's text in `locale`. Each language's articles are their own lazy
 * chunk (generated by scripts/generate-blog-content.js), so a Bulgarian post
 * never downloads the English texts and the other way round.
 */
export const articleIn = (locale: Locale): ResolveFn<ArticleData> => async (route) => {
  const slug = route.paramMap.get('slug') ?? '';
  const source = (await postSource(slug, locale)) ?? slug;
  if (locale === DEFAULT_LOCALE) {
    const { BLOG_CONTENT } = await import('../../services/blog-content.generated');
    return { source, text: BLOG_CONTENT[slug] };
  }
  const { TRANSLATED_BLOG_CONTENT } = await import('../../services/blog-content.translations.generated');
  return { source, text: TRANSLATED_BLOG_CONTENT[locale]?.[slug] };
};

/**
 * The one route of a language's blog that serves every post in it — the
 * registry (blog-posts.registry.ts) in Bulgarian, `translatedPosts` in
 * src/i18n/locales.json elsewhere. A new post needs no route; the prerender
 * list comes from the same sources (app.routes.server.ts).
 */
export const articleRoute = (locale: Locale): Route => ({
  path: ':slug',
  canMatch: [isPostIn(locale)],
  resolve: { article: articleIn(locale) },
  loadComponent: () => import('./article.component').then((m) => m.BlogArticleComponent)
});
